export const getSelectableDistrictValue = (
  regionId: string,
  supportedDistricts: readonly FarmerDistrictValue[]
): FarmerDistrictValue | null => {
  const value = SRI_LANKA_DISTRICT_REGIONS.find(
    (region) => region.id === regionId
  )?.value;

  return value && supportedDistricts.includes(value) ? value : null;
};

